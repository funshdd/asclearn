/**
  ******************************************************************************
  * @file    config.h
  * @brief   STC89C52RC 电子密码锁 —— 全局配置（引脚 / 时序 / 编译开关）
  *
  * 开发板：野火 STC89C52RC（11.0592MHz）
  *
  * 引脚分配（与配套 2-配套程序 BSP 头文件一致）：
  *   数码管段码      P0            （经 74HC245 驱动，共阴极段码）
  *   数码管位选      P2.2/P2.3/P2.4 （74HC138 的 A/B/C）
  *   矩阵键盘        P1 低四位为列输出、高四位为行输入
  *   矩阵键盘使能    P2.0           （必须为低，屏蔽 RTC_RST 复用影响）
  *   蜂鸣器          P1.5           （与矩阵键盘第 3 行复用，见 key.c）
  *   反馈灯 D7       P2.6           （低电平点亮）
  *   版本灯 D8       P2.7           （A 版常暗=1，B 版常亮=0）
  *   串口            P3.0/P3.1      （9600 8N1）
  ******************************************************************************
  */

#ifndef __CONFIG_H
#define __CONFIG_H

#include <reg52.h>

/* ============================ 编译开关 ============================ */

/* D8(P2.7) 版本选择：
 *   0 -> A 版，D8 常暗（P2.7 = 1）
 *   1 -> B 版，D8 常亮（P2.7 = 0）
 * 两份 HEX 除该宏外完全相同。
 */
#ifndef D8_ALWAYS_ON
#define D8_ALWAYS_ON        0
#endif

/* 蜂鸣器类型：0 = 无源（1ms 节拍翻转产生 500Hz 方波）
 *             1 = 有源（直接给电平） */
#define BEEP_ACTIVE         0

/* 矩阵键盘编号方式：
 *   1 = 行优先：键号 = 行*4 + 列 + 1（与题面 S1~S16 表格一致，默认）
 *   0 = 列优先：键号 = 列*4 + 行 + 1（C51 参考例程的写法，会出现主对角线镜像）
 * 若实机按键功能整体镜像，把这里改一下即可。 */
#define KEY_INDEX_ROW_MAJOR 1

/* 固件版本号（VERSION 命令回复用） */
#define VERSION_STR         "1.0"

/* ============================ 引脚定义 ============================ */

/* 数码管 */
#define SEG_PORT            P0
sbit NIX_A = P2^2;
sbit NIX_B = P2^3;
sbit NIX_C = P2^4;

/* 矩阵键盘 */
#define KEY_PORT            P1
sbit KEY_EN = P2^0;         /* 拉低使能矩阵键盘 */

/* 蜂鸣器 */
sbit BEEP = P1^5;

/* 反馈灯 / 版本灯 */
sbit LED_FB = P2^6;         /* 低电平点亮 */
sbit LED_D8 = P2^7;         /* 低电平点亮 */

/* ============================ 业务参数 ============================ */

#define MAX_DIGITS          6       /* 密码位数 */
#define TMO_AUTO_LOCK       15      /* 自动上锁秒数 */
#define TMO_WAIT            30      /* 第三次错误的暂停秒数 */
#define TMO_PROTECT         60      /* 第五次错误的保护秒数 */
#define ERR_LIMIT_WAIT      3
#define ERR_LIMIT_PROTECT   5

#define MAX_CMD_LEN         16      /* 串口正文最大字节数 */

/* ============================ 人机反馈 ============================ */

#define BEEP_MS_KEY         25      /* 按键提示音时长(ms) */
#define BEEP_MS_CMD         20      /* 串口命令提示音时长(ms) */
#define LED_MS_FB           60      /* 反馈灯点亮时长(ms) */

/* ============================ 段码 ============================ */

#define SEG_DASH            0x40    /* '-' */
#define SEG_BLANK           0x00    /* 熄灭 */

#endif /* __CONFIG_H */
